/// `glyph` at `size` points, in the text color around it.
pub fn glyph(glyph: Glyph, size: f32) -> Svg {
    let markup = format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor"><path d="{}"/></svg>"#,
        glyph.path()
    );
    svg(ImageSrc::svg_markup(&markup)).w(px(size)).h(px(size))
}
