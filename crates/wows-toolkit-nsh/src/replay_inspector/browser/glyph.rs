/// The drawing of one of `wows_toolkit_viewmodel::glyphs`.
pub(super) fn markup(glyph: &str) -> Option<&'static str> {
    match glyph {
        glyphs::CLOCK => Some(CLOCK),
        glyphs::CROSSHAIR_SIMPLE => Some(CROSSHAIR_SIMPLE),
        glyphs::SWORD => Some(SWORD),
        glyphs::USERS_THREE => Some(USERS_THREE),
        _ => None,
    }
}
